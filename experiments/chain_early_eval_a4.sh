#!/usr/bin/env bash
# 1. Benchmark the EARLY checkpoints (s50/s100/s150) of a3 and a2pc.
# 2. Then launch a4 = a3 with lam_fresh raised 1.0 -> 4.0.
#
# Why early checkpoints: s200 was the best of {200,250,300} on every K=1 metric
# and K=1 degrades monotonically with training, so the optimum may sit earlier
# still.  The checkpoints already exist; only the bench time is new.
#
# Why lam_fresh=4: L_fresh IS the K=1 branch (banks are built with K_t=1, so the
# fresh rollout is dense) and walk already gives it the full 80->320 depth
# sweep.  What it cannot do at lam_fresh=1.0 is outvote the K=28 long branch,
# which is weighted equally every step.  4.0 tests whether the drift is a matter
# of coverage (already fixed) or of weight (not yet tested).
#
#   tmux new-session -d -s early_a4 experiments/chain_early_eval_a4.sh
set -u
cd "$(dirname "$0")/.."
LOG=experiments/logs/chain_a4.log
exec > >(tee -a "$LOG") 2>&1
log() { echo "[$(date '+%F %T')] $*"; }

EARLY_STEPS="50 100 150"
EARLY_RUNS="a3 a2pc"

METHODS=""
for R in $EARLY_RUNS; do
  for S in $EARLY_STEPS; do
    SRC="ckpt_train/${R}.step${S}.pt" DST="bench_ckpt/sd_${R}_step${S}.pt"
    if [ ! -f "$SRC" ]; then log "MISSING $SRC"; continue; fi
    if [ ! -f "$DST" ]; then
      log "exporting $SRC -> $DST"
      python experiments/_strip_optim.py "$SRC" "$DST" || { log "EXPORT FAILED $SRC"; continue; }
    fi
    for V in h64 k28; do
      DSTC="benchmark/configs/methods/sd_${R}s${S}_${V}.yaml"
      if [ ! -f "$DSTC" ]; then
        sed -e "s|sd_a2_step250\.pt|sd_${R}_step${S}.pt|" \
            -e "s|^# self-distilled A2 preset, step 250.*|# ${R} step ${S} -- generated by chain_early_eval_a4.sh|" \
            "benchmark/configs/methods/sd_a2s250_${V}.yaml" > "$DSTC"
        log "wrote $DSTC"
      fi
      METHODS="$METHODS  - sd_${R}s${S}_${V}\n"
    done
  done
done

if [ -z "$METHODS" ]; then
  log "NO early method configs -- skipping straight to a4"
else
  {
    echo "# Oxford Spires - EARLY checkpoints (s50/s100/s150) of a3 (walk) and a2pc (window)."
    echo "# Locates the K=1 optimum, which s200/s250/s300 showed is before step 300."
    echo "workspace: /NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws/oxford"
    echo ""
    echo "datasets:"
    echo "  - oxford"
    echo ""
    echo "methods:"
    printf "%b" "$METHODS"
    echo "evaluation:"
    echo "  traj:"
    echo "    enable: true"
    echo "    vis: true"
    echo "  auc:"
    echo "    enable: true"
    echo "    vis: true"
    echo "    aggregation: both"
    echo "  depth:"
    echo "    enable: false"
    echo "  points:"
    echo "    enable: false"
  } > benchmark/configs/oxford_early.yaml
  log "wrote benchmark/configs/oxford_early.yaml"
  log "Oxford run phase (early checkpoints)"
  benchmark/bench.sh run configs/oxford_early.yaml --debug || log "BENCH RUN FAILED"
  log "Oxford evaluate phase (early checkpoints)"
  benchmark/bench.sh evaluate configs/oxford_early.yaml --debug || log "BENCH EVALUATE FAILED"
  log "early-checkpoint eval done"
fi

# ------------------------------------------------------------------- a4 train
# Identical to a3 in every respect except lam_fresh: walk, A1PC, l2sp 0, same
# base ckpt, same 10 scenes, same DDP, same 300 steps.
sleep 20
log "launching a4 -- walk, A1PC, lam_fresh=4.0, 300 steps"
STEPS=300 experiments/launch_ddp.sh a4 \
  --preset A1PC --lam_fresh 4.0 --l2sp 0 --fresh_mode walk
log "a4 launched -- tmux attach -t train_a4"
