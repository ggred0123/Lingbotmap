#!/usr/bin/env bash
# The v6bench five-dataset suite, run for v7f at the 'auto' keyframe setting.
#
# ★ WHY 'auto' AND NOT _k1.  auto resolves to K = ceil(N/320), so these five
# datasets deploy at K = 1 (ETH3D 38, Neural RGB-D, 7-Scenes) through K = 12
# (Oxford stride 1, 3840 frames) and K = 38 (VBR, 12042).  That is the axis the
# training-side cache audit says is under-supervised: at K = 28 only 5% of
# supervised windows ever reach the deployed 64-keyframe cache depth, against
# 100% at K = 1.  Running these at _k1 would erase exactly the variable.
#
# ★ THE STEP GRID IS v6bench's PLUS 300.  150/600/1200 are what sd_v6f* and
# sd_v6a* already occupy in these workspaces, so v7f rows drop straight into the
# existing tables; 300 is added because it is where v7f's Oxford K=1 curve
# bottoms out (ATE 6.176), and a suite that skipped its own optimum could only
# understate the cell.
#
# ★ OXFORD STRIDE-1 IS DELIBERATELY NOT IN THIS SUITE.  It is the second most
# expensive card here (48 min/method) and its v6 arm is already the weakest
# comparison in the workspace, so the four remaining datasets carry the length
# ladder -- 32 frames (ETH3D) to 11,671 (VBR) -- without it.
#
# ★ THE SPLIT IS BY COST, NOT BY DATASET.  Measured per-method wall time from
# the v6bench runs: eth3d 0.3 min, neural_rgbd 3.7, seven_scenes 6.0,
# oxford_long 48, vbr 110.  Handing one card VBR and the other everything else
# is 440 vs 232 minutes; halving the two expensive datasets across both cards
# instead is ~316 vs ~356, which is the difference between a 7.3 h and a 5.9 h
# wall clock.
#
# ★ RE-RUNNABLE.  bench.sh writes .complete.json per (scene, method); a kill
# costs only the scene in flight.  base_auto is already complete in all five
# workspaces from v6bench and is listed for the evaluate phase only.
#
#   experiments/eval_v7f_bench.sh              # export + run + evaluate
#   DRY=1 experiments/eval_v7f_bench.sh        # show the plan only
#   NAME=v7e experiments/eval_v7f_bench.sh     # same suite for another run
set -u
cd "$(dirname "$0")/.."
NAME=${NAME:-v7f}
STEPS_LIST=${STEPS_LIST:-"150 300 600 1200"}
log(){ echo "[$(date '+%H:%M:%S')] [bench $NAME] $*"; }

WS_ROOT=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws

# ── export weights + one 'auto' method config each ───────────────────────────
METHODS=""
for S in $STEPS_LIST; do
  SRC="ckpt_train/${NAME}.step${S}.pt"
  [ -f "$SRC" ] || { log "MISSING $SRC -- skipping step $S"; continue; }
  DST="bench_ckpt/sd_${NAME}_step${S}.pt"
  [ -f "$DST" ] || { log "export step $S"; python experiments/_strip_optim.py \
      "$SRC" "$DST" >/dev/null || { log "EXPORT FAILED $S"; continue; }; }
  M="sd_${NAME}s${S}_auto"
  CFG="benchmark/configs/methods/${M}.yaml"
  [ -f "$CFG" ] || sed "s|^_checkpoint:.*|_checkpoint: $(pwd)/${DST}|" \
      benchmark/configs/methods/sd_v6fs600_auto.yaml > "$CFG"
  METHODS="$METHODS $M"
done
set -- $METHODS
log "$# methods:$METHODS"
[ $# -gt 0 ] || { log "no methods -- nothing to do"; exit 1; }

# first half / second half of the method list, for splitting the costly datasets
H1=""; H2=""; n=0
for m in "$@"; do n=$(( n + 1 )); if [ $(( (n + 1) / 2 * 2 )) -eq $n ]; then H2="$H2 $m"; else H1="$H1 $m"; fi; done

mk(){ # $1=file  $2=dataset  $3=workspace  rest=methods
  local f=$1 ds=$2 ws=$3; shift 3
  { echo "# generated by experiments/eval_v7f_bench.sh"
    echo "workspace: $ws"
    echo "datasets:"; echo "  - $ds"; echo "methods:"
    for m in "$@"; do echo "  - $m"; done
    echo "evaluation:"
    echo "  traj: {enable: true, vis: false}"
    echo "  auc: {enable: true, vis: false, aggregation: both}"
    echo "  depth: {enable: false}"; echo "  points: {enable: false}"
  } > "$f"
}

# costly pair -> split by method half; cheap three -> whole list on card 1
mk benchmark/configs/${NAME}bench_vbr_a.yaml          vbr          $WS_ROOT/vbr          $H1
mk benchmark/configs/${NAME}bench_vbr_b.yaml          vbr          $WS_ROOT/vbr          $H2
mk benchmark/configs/${NAME}bench_eth3d.yaml          eth3d        $WS_ROOT/eth3d        "$@"
mk benchmark/configs/${NAME}bench_neural_rgbd.yaml    neural_rgbd  $WS_ROOT/neural_rgbd  "$@"
mk benchmark/configs/${NAME}bench_seven_scenes.yaml   seven_scenes $WS_ROOT/seven_scenes "$@"
# evaluate-only config carries base_auto too, so the table aggregates against it
mk benchmark/configs/${NAME}bench_vbr_all.yaml        vbr          $WS_ROOT/vbr          base_auto "$@"

log "card0 lane:$H1 on vbr, then eth3d + neural_rgbd"
log "card1 lane:$H2 on vbr, then seven_scenes"
[ "${DRY:-0}" = "1" ] && { log "DRY=1: stopping before any scoring"; exit 0; }

cd benchmark
F="Combination \(|Successful:|Total failed|already complete|rror|Traceback"
run_lane(){ # $1=gpu  rest=configs
  local g=$1; shift
  for c in "$@"; do
    echo "[gpu$g] >>> $c"
    GPU=$g THREADS=8 ./bench.sh run "configs/$c.yaml" 2>&1 | grep -aE "$F" | sed -u "s/^/[gpu$g] /"
  done
}
run_lane 0 ${NAME}bench_vbr_a ${NAME}bench_eth3d ${NAME}bench_neural_rgbd & PA=$!
run_lane 1 ${NAME}bench_vbr_b ${NAME}bench_seven_scenes & PB=$!
wait $PA; log "card0 done"
wait $PB; log "card1 done"

log "=== EVALUATE ==="
for c in ${NAME}bench_vbr_all \
         ${NAME}bench_eth3d ${NAME}bench_neural_rgbd ${NAME}bench_seven_scenes; do
  echo "--- evaluate $c ---"
  GPU=1 ./bench.sh evaluate "configs/$c.yaml" 2>&1 \
    | grep -aE "Total success|Total failed|rror|Traceback"
done
log "V7FBENCH_DONE"
