#!/usr/bin/env bash
# a3 (walk) -> Oxford K=1 vs K=28 eval -> a2pc (window) from scratch.
#
# a2 is not a usable control for a3: its first 50 steps ran preset=A1 and only
# the resume switched to A1PC (train_a2.log lines 26/182).  a2pc is the exact
# twin of a3 -- same base ckpt, same A1PC, same 10 scenes, same DDP -- differing
# only in --fresh_mode, which is the one thing under test.
#
# Both runs stop at step 300, which is as far as a2 ever got.  Past that there is
# nothing to compare against, so the extra ~14 h of 1200 steps buys no answer.
#
#   tmux new-session -d -s chain_a3 experiments/chain_a3_eval_a2pc.sh
set -u
cd "$(dirname "$0")/.."
LOG=experiments/logs/chain_a3.log
exec > >(tee -a "$LOG") 2>&1
log() { echo "[$(date '+%F %T')] $*"; }

STOP_STEP=300
STEPS_TO_EVAL="200 250 300"

log "waiting for train_a3 to finish (stopper kills it at step $STOP_STEP)"
while tmux has-session -t train_a3 2>/dev/null; do sleep 60; done
log "train_a3 is gone"
sleep 30

# ---------------------------------------------------------------- export ckpts
# Optimizer state stripped, weights byte-identical (setup_local/README.md:77).
# a2's step300 is exported too: it already exists on disk but was never
# benchmarked, so it costs nothing and gives both arms the same three points.
export_ck() {  # $1=run name  $2=step
  local SRC="ckpt_train/$1.step$2.pt" DST="bench_ckpt/sd_$1_step$2.pt"
  if [ ! -f "$SRC" ]; then log "MISSING $SRC -- skipping"; return 1; fi
  if [ -f "$DST" ]; then log "$DST already exists"; return 0; fi
  log "exporting $SRC -> $DST"
  python experiments/_strip_optim.py "$SRC" "$DST" || { log "EXPORT FAILED $SRC"; return 1; }
}

for S in $STEPS_TO_EVAL; do export_ck a3 "$S" || true; done
export_ck a2 300 || true

# -------------------------------------------------------------- method configs
# h64 = auto keyframe (K=1 on Oxford's 320-frame scenes), k28 = forced K=28.
# Templates are the existing sd_a2s250_* pair; only _checkpoint changes.
mk_cfg() {  # $1=run  $2=step
  local R=$1 S=$2 V
  [ -f "bench_ckpt/sd_${R}_step${S}.pt" ] || return 1
  for V in h64 k28; do
    local SRCC="benchmark/configs/methods/sd_a2s250_${V}.yaml"
    local DSTC="benchmark/configs/methods/sd_${R}s${S}_${V}.yaml"
    [ -f "$DSTC" ] && { log "$DSTC exists"; continue; }
    sed -e "s|sd_a2_step250\.pt|sd_${R}_step${S}.pt|" \
        -e "s|^# self-distilled A2 preset, step 250.*|# ${R} step ${S} -- generated by chain_a3_eval_a2pc.sh|" \
        "$SRCC" > "$DSTC"
    log "wrote $DSTC"
  done
}

METHODS=""
for S in $STEPS_TO_EVAL; do
  mk_cfg a3 "$S" || continue
  for V in h64 k28; do METHODS="$METHODS  - sd_a3s${S}_${V}\n"; done
done
# a2 s200/s250 are already evaluated in bench_ws; only s300 is new.
if mk_cfg a2 300; then
  for V in h64 k28; do METHODS="$METHODS  - sd_a2s300_${V}\n"; done
fi

# ---------------------------------------------------------------- bench config
if [ -z "$METHODS" ]; then
  log "NO METHOD CONFIGS -- skipping the Oxford eval entirely"
else
  {
    echo "# Oxford Spires - A3 (fresh_mode=walk) vs A2 step300, K=1 (h64/auto) vs K=28."
    echo "# --debug evaluates only bodleian-library-02, matching base/sd_a1/sd_a2s200/s250."
    echo "workspace: /NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws/oxford"
    echo ""
    echo "datasets:"
    echo "  - oxford"
    echo ""
    echo "methods:"
    printf "%b" "$METHODS"
    echo "evaluation:"
    echo "  traj:"
    echo "    enable: true"
    echo "    vis: true"
    echo "  auc:"
    echo "    enable: true"
    echo "    vis: true"
    echo "    aggregation: both"
    echo "  depth:"
    echo "    enable: false"
    echo "  points:"
    echo "    enable: false"
  } > benchmark/configs/oxford_a3.yaml
  log "wrote benchmark/configs/oxford_a3.yaml with:"
  grep -a "^  - " benchmark/configs/oxford_a3.yaml | tr -d ' ' | tr '\n' ' '; echo

  log "Oxford run phase"
  benchmark/bench.sh run configs/oxford_a3.yaml --debug || log "BENCH RUN FAILED"
  log "Oxford evaluate phase"
  benchmark/bench.sh evaluate configs/oxford_a3.yaml --debug || log "BENCH EVALUATE FAILED"
  log "Oxford eval done"
fi

# ------------------------------------------------------------------- a2pc train
# Launched regardless of eval outcome: it does not depend on the eval result and
# idle B200s are the expensive failure mode.  STEPS matches a3's stop point.
sleep 20
log "launching a2pc -- A1PC, window mode, from the base ckpt, $STOP_STEP steps"
STEPS=$STOP_STEP experiments/launch_ddp.sh a2pc \
  --preset A1PC --lam_fresh 1.0 --l2sp 0 --fresh_mode window
log "chain done -- tmux attach -t train_a2pc"
