#!/usr/bin/env bash
# Second half of the campaign: once a2pc (window control) finishes, benchmark it
# on the same Oxford K=1 vs K=28 axis a3 was measured on.
#
# Kept separate from chain_a3_eval_a2pc.sh because that one is already running
# and bash re-reads a script by byte offset -- editing a live script corrupts it.
#
#   tmux new-session -d -s chain_a2pc experiments/chain_a2pc_eval.sh
set -u
cd "$(dirname "$0")/.."
LOG=experiments/logs/chain_a3.log
exec > >(tee -a "$LOG") 2>&1
log() { echo "[$(date '+%F %T')] [a2pc-eval] $*"; }

STEPS_TO_EVAL="200 250 300"

log "waiting for train_a2pc to be launched by chain_a3"
while ! tmux has-session -t train_a2pc 2>/dev/null; do sleep 60; done
log "train_a2pc is up -- now waiting for it to finish"
while tmux has-session -t train_a2pc 2>/dev/null; do sleep 60; done
log "train_a2pc is gone"
sleep 30

METHODS=""
for S in $STEPS_TO_EVAL; do
  SRC="ckpt_train/a2pc.step${S}.pt" DST="bench_ckpt/sd_a2pc_step${S}.pt"
  if [ ! -f "$SRC" ]; then log "MISSING $SRC -- skipping step $S"; continue; fi
  if [ ! -f "$DST" ]; then
    log "exporting $SRC -> $DST"
    python experiments/_strip_optim.py "$SRC" "$DST" || { log "EXPORT FAILED $SRC"; continue; }
  fi
  for V in h64 k28; do
    DSTC="benchmark/configs/methods/sd_a2pcs${S}_${V}.yaml"
    if [ ! -f "$DSTC" ]; then
      sed -e "s|sd_a2_step250\.pt|sd_a2pc_step${S}.pt|" \
          -e "s|^# self-distilled A2 preset, step 250.*|# a2pc step ${S} (window control) -- generated by chain_a2pc_eval.sh|" \
          "benchmark/configs/methods/sd_a2s250_${V}.yaml" > "$DSTC"
      log "wrote $DSTC"
    fi
    METHODS="$METHODS  - sd_a2pcs${S}_${V}\n"
  done
done

if [ -z "$METHODS" ]; then
  log "NO a2pc METHOD CONFIGS -- nothing to evaluate"
  exit 1
fi

{
  echo "# Oxford Spires - a2pc (window control, A1PC from scratch), K=1 vs K=28."
  echo "# --debug evaluates only bodleian-library-02, matching every other arm."
  echo "workspace: /NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws/oxford"
  echo ""
  echo "datasets:"
  echo "  - oxford"
  echo ""
  echo "methods:"
  printf "%b" "$METHODS"
  echo "evaluation:"
  echo "  traj:"
  echo "    enable: true"
  echo "    vis: true"
  echo "  auc:"
  echo "    enable: true"
  echo "    vis: true"
  echo "    aggregation: both"
  echo "  depth:"
  echo "    enable: false"
  echo "  points:"
  echo "    enable: false"
} > benchmark/configs/oxford_a2pc.yaml
log "wrote benchmark/configs/oxford_a2pc.yaml with:"
grep -a "^  - " benchmark/configs/oxford_a2pc.yaml | tr -d ' ' | tr '\n' ' '; echo

log "Oxford run phase"
benchmark/bench.sh run configs/oxford_a2pc.yaml --debug || log "BENCH RUN FAILED"
log "Oxford evaluate phase"
benchmark/bench.sh evaluate configs/oxford_a2pc.yaml --debug || log "BENCH EVALUATE FAILED"
log "CAMPAIGN COMPLETE -- all arms in bench_ws/oxford/oxford/bodleian-library-02/"
