#!/usr/bin/env bash
# The spine 2x2, re-run on a corpus that is actually video.
#
#   c0off   p_identity = 1.0   identity branch only   (off-policy)
#   c0on    p_identity = 0.0   correction branch only (on-policy)
#
# The original pair (s0off / s0on) trained on a corpus where 65% of the sampling
# weight was not video, and the correction branch was hit hardest because it
# rolls the student THROUGH those frames.  Its headline -- on-policy causes scale
# collapse -- therefore has a mundane rival explanation.  This decides it.
#
# ★ ARMS RUN SEQUENTIALLY over both cards, and arm 1 is scored WHILE arm 2
# trains, under a memory cap.  Two rules carried over from chain_spine2.sh: the
# trainer reaches steady state before any bench touches a card, and every bench
# runs capped -- a bench there grew 7.9 GB to 140 GB in six minutes and killed a
# twelve-hour run.
set -u
cd "$(dirname "$0")/.."
WS=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws
STEPS_K1=${STEPS_K1:-"50 100 200 300 400 500 600 700 800 900 1000 1100 1200 1250"}
STEPS_LONG=${STEPS_LONG:-"300 1200"}
CAP=${BENCH_GPU_MEM_FRACTION:-0.27}
PHASE=${PHASE:-all}
log(){ echo "[$(date '+%m-%d %H:%M:%S')] [clean2x2] $*"; }

train_step(){ grep -aoE '^ *\[ *[0-9]+\]' "experiments/logs/train_$1.log" 2>/dev/null | tail -1 | tr -dc 0-9; }
train_done(){
  python3 - "$1" <<'PY' 2>/dev/null
import json, sys
try: d = json.load(open(f"experiments/results/train_{sys.argv[1]}.json"))
except Exception: sys.exit(1)
sys.exit(0 if d.get("wall_s") else 1)
PY
}
# ★ ASK THE PROCESS TABLE, NOT TMUX.  The arms now run under setsid (see
# launch_clean.sh) because a login-session cleanup reaped the tmux server and a
# 540-step run with it.  --wandb_name is unique per arm, so it is the handle.
alive(){ pgrep -f -- "--wandb_name $1" >/dev/null 2>&1; }
no_trainer(){ ! pgrep -f "lingbot_map.train.trainer" >/dev/null 2>&1; }

wait_arm(){
  local n=$1 t=0
  log "waiting for $n"
  while [ "$t" -lt 259200 ]; do
    train_done "$n" && { log "$n finished"; return 0; }
    alive "$n" || { log "ABORT: $n died at step $(train_step "$n")"; return 1; }
    sleep 120; t=$((t+120))
    [ $((t % 1800)) -eq 0 ] && log "  ... $n at step $(train_step "$n")"
  done
  log "TIMEOUT on $n"; return 1
}
wait_steady(){
  local n=$1 want=$2
  log "waiting for $n to reach step $want before any bench starts"
  while :; do
    train_done "$n" && return 0
    local s; s=$(train_step "$n")
    [ -n "${s:-}" ] && [ "$s" -ge "$want" ] && { log "$n at step $s -- steady"; return 0; }
    alive "$n" || { log "ABORT: $n is not running"; return 1; }
    sleep 60
  done
}
pick_gpu(){
  nvidia-smi --query-gpu=index,memory.free --format=csv,noheader,nounits \
    | sort -t, -k2 -n -r | head -1 | cut -d, -f1 | tr -d ' '
}
mk_method(){ # $1=name $2=step $3=k1|auto
  local n=$1 s=$2 kind=$3
  local src=ckpt_train/$n.step$s.pt dst=bench_ckpt/sd_${n}_step$s.pt
  [ -f "$src" ] || return 1
  [ -f "$dst" ] || python3 experiments/_strip_optim.py "$src" "$dst" >/dev/null 2>&1 || return 1
  local m tmpl
  if [ "$kind" = "k1" ]; then m=sd_${n}s${s}_k1; tmpl=sd_v6gs50_k1.yaml
  else                        m=sd_${n}s${s}_auto; tmpl=sd_v6fs600_auto.yaml; fi
  local cfg=benchmark/configs/methods/$m.yaml
  [ -f "$cfg" ] || sed "s|^_checkpoint:.*|_checkpoint: $(pwd)/$dst|" \
      "benchmark/configs/methods/$tmpl" > "$cfg"
  echo "$m"
}
mk_cfg(){
  local f=$1 ds=$2 ws=$3; shift 3
  { echo "# generated by experiments/chain_spine_clean.sh"
    echo "workspace: $ws"; echo "datasets:"; echo "  - $ds"; echo "methods:"
    for m in "$@"; do echo "  - $m"; done
    echo "evaluation:"
    echo "  traj: {enable: true, vis: false}"
    echo "  auc: {enable: true, vis: false, aggregation: both}"
    echo "  depth: {enable: false}"; echo "  points: {enable: false}"
  } > "$f"
}
run_bench(){
  local c=$1 g; g=$(pick_gpu); g=${g:-1}
  log "run $c (gpu$g, cap $CAP)"
  GPU=$g THREADS=8 BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh run "configs/$c.yaml" 2>&1 \
    | grep -a --line-buffered -E "Combination \(|Successful:|Total failed|out of memory|rror|Traceback" \
    | sed -u "s/^/  [$c] /"
  GPU=$g BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh evaluate "configs/$c.yaml" 2>&1 \
    | grep -aE "Total success|Total failed|rror" | sed -u "s/^/  [$c] /"
}
score_arm(){
  local n=$1 M="" L=""
  for s in $STEPS_K1;   do m=$(mk_method "$n" "$s" k1)   && M="$M $m"; done
  for s in $STEPS_LONG; do m=$(mk_method "$n" "$s" auto) && L="$L $m"; done
  [ -n "$M" ] && { mk_cfg benchmark/configs/clean_oxford_$n.yaml oxford $WS/oxford base_k1 $M
                   run_bench clean_oxford_$n; report; }
  [ -n "$L" ] && { mk_cfg benchmark/configs/clean_oxlong_$n.yaml oxford_long $WS/oxford_long base_auto $L
                   run_bench clean_oxlong_$n; report; }
}
report(){ python3 experiments/mk_spine_report.py >/dev/null 2>&1; }

case "$PHASE" in
  train|all)
    log "=== arm 1: c0off (identity only, p_identity=1.0) ==="
    train_done c0off || alive c0off || experiments/launch_clean.sh c0off 1.0
    wait_arm c0off || exit 1
    for _ in $(seq 30); do no_trainer && break; sleep 20; done

    log "=== arm 2: c0on (correction only, p_identity=0.0), arm 1 scored alongside ==="
    train_done c0on || alive c0on || experiments/launch_clean.sh c0on 0.0
    wait_steady c0on 80 || exit 1
    score_arm c0off
    wait_arm c0on || exit 1
    ;;
esac
case "$PHASE" in
  eval|all)
    for _ in $(seq 30); do no_trainer && break; sleep 20; done
    log "=== scoring arm 2 ==="
    score_arm c0on
    ;;
esac
log "CLEAN2X2_DONE"
