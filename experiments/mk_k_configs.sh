#!/usr/bin/env bash
# Benchmark method configs across a keyframe grid -- docs/self-distill-ver5.md
# "Evaluation".
#
# The grid is chosen so both datasets land in a comparable band of PHYSICAL
# baseline, not so the K labels match.  Measured with experiments/kf_baseline.py
# (median inter-keyframe motion):
#
#   Oxford, loader stride 12       MCD kth_day_06, stride 1
#     K=1   1.71 m /  5.9 deg        K=1    0.16 m / 1.8 deg
#     K=2   3.42 m /  7.2 deg        K=4    0.64 m / 4.3 deg
#     K=3   5.14 m /  8.1 deg        K=8    1.28 m / 4.4 deg
#     K=4   6.85 m /  8.9 deg        K=12   1.92 m / 5.4 deg
#     K=8  13.68 m / 10.1 deg  <-.   K=28   4.49 m / 6.4 deg
#     K=28 44.17 m / 54.1 deg  <-'   out of range: reported, never gated
#
# So Oxford {1,2,3,4} and MCD {1,4,8,12,28} span roughly the same 0.16-6.9 m,
# and Oxford K>=8 does not.  v5: "It is reported for completeness and is never
# an optimization target or a gate."
#
#   experiments/mk_k_configs.sh base                      # K = 1 2 3 4
#   KS="1 2 3 4 8 28" experiments/mk_k_configs.sh v5s300
#   CKPT=bench_ckpt/sd_v5_step300.pt experiments/mk_k_configs.sh v5s300
set -u
cd "$(dirname "$0")/.."

CFG=benchmark/configs/methods
KS=${KS:-"1 2 3 4"}
TEMPLATE=${TEMPLATE:-$CFG/base_k3.yaml}
BASE_CKPT=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/ckpt/lingbot-map.pt

[ "$#" -ge 1 ] || { echo "usage: $0 <method-name> [<method-name> ...]"; exit 1; }
[ -f "$TEMPLATE" ] || { echo "no template $TEMPLATE"; exit 1; }

for name in "$@"; do
  case "$name" in
    base) CK=${CKPT:-$BASE_CKPT} ;;
    *)    CK=${CKPT:-bench_ckpt/sd_${name%s*}_step${name##*s}.pt} ;;
  esac
  CK=$(readlink -f "$CK" 2>/dev/null || echo "$CK")
  if [ ! -f "$CK" ]; then
    echo "[skip] $name -- no checkpoint at $CK"
    continue
  fi
  for K in $KS; do
    OUT=$CFG/${name}_k${K}.yaml
    if [ -f "$OUT" ]; then echo "[have] $OUT"; continue; fi
    # Only two lines differ from the template: the checkpoint and the interval.
    # Everything else -- sliding window, scale frames, area budget -- must stay
    # identical or the comparison across K stops being a comparison across K.
    sed -e "s|^_checkpoint:.*|_checkpoint: $CK|" \
        -e "s|^_keyframe_interval:.*|_keyframe_interval: $K   # v5 eval grid; see experiments/kf_baseline.py|" \
        -e "1s|^#.*|# ${name} at K=${K} -- generated by experiments/mk_k_configs.sh|" \
        "$TEMPLATE" > "$OUT"
    echo "[wrote] $OUT"
  done
done
