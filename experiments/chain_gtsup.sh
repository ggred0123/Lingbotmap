#!/usr/bin/env bash
# The decisive cell: is it the OBJECTIVE or the LABELS?
#
# Every run in this project so far trained against base-model pseudo labels, so
# "the loss is inadequate" and "the labels are bad" have never been separated.
# MCD carries GT, so they can be.  Two arms, identical in every respect except
# where pose_enc comes from:
#
#   gtsup    labels/<scene>_gt   GT camera poses, put into the teacher's gauge
#   teasup   labels/<scene>      the base model's pseudo labels
#
# If gtsup holds while teasup degrades, the objective is fine and the work goes
# to the data side -- the stitcher and the gauge.  If gtsup degrades too, GT
# cannot save this objective and the loss itself has to change.
#
# ★ ARMS RUN SEQUENTIALLY over both cards (see launch_gtsup.sh for why one card
# each is not available).  So this borrows chain_spine2.sh's shape: arm 1 is
# scored WHILE arm 2 trains, under a memory cap, which is where the clock is won
# back.  Two rules from that chain still hold -- the trainer reaches steady
# state before any bench touches a card, and every bench runs capped, so the
# worst case is a slow bench rather than a dead ten-hour run.
#
#   experiments/chain_gtsup.sh              # full chain
#   PHASE=eval experiments/chain_gtsup.sh   # scoring only
set -u
cd "$(dirname "$0")/.."

WS=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws
STEPS_K1=${STEPS_K1:-"50 100 200 300 400 500 600 700 800 900 1000 1100 1200 1250"}
STEPS_LONG=${STEPS_LONG:-"300 1200"}
CAP=${BENCH_GPU_MEM_FRACTION:-0.27}  # proven in chain_spine2.sh: a bench grew 7.9 -> 140 GB in six minutes and killed a trainer
PHASE=${PHASE:-all}
PY=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/.venv-bench/bin/python
log(){ echo "[$(date '+%m-%d %H:%M:%S')] [gtsup] $*"; }

train_step(){ grep -aoE '^ *\[ *[0-9]+\]' "experiments/logs/train_$1.log" 2>/dev/null | tail -1 | tr -dc 0-9; }

train_done(){ # wall_s is written once, at the end -- the only field that means finished
  python3 - "$1" <<'PY' 2>/dev/null
import json, sys
try:
    d = json.load(open(f"experiments/results/train_{sys.argv[1]}.json"))
except Exception:
    sys.exit(1)
sys.exit(0 if d.get("wall_s") else 1)
PY
}

alive(){ tmux has-session -t "train_$1" 2>/dev/null; }

no_trainer_running(){
  [ "$(ps -eo args | grep -c '[l]ingbot_map.train.trainer')" = "0" ]
}

wait_arm(){ # $1=name -- and notice when it dies rather than waiting three days
  local n=$1 t=0
  log "waiting for $n"
  while [ "$t" -lt 259200 ]; do
    train_done "$n" && { log "$n finished"; return 0; }
    alive "$n" || { log "ABORT: $n died at step $(train_step "$n")"; return 1; }
    sleep 120; t=$((t+120))
    [ $((t % 1800)) -eq 0 ] && log "  ... $n at step $(train_step "$n")"
  done
  log "TIMEOUT on $n"; return 1
}

wait_steady(){ # $1=name $2=step -- no bench touches a card before this
  local n=$1 want=$2 t=0
  log "waiting for $n to reach step $want before any bench starts"
  while :; do
    train_done "$n" && { log "$n already finished"; return 0; }
    local s; s=$(train_step "$n")
    [ -n "${s:-}" ] && [ "$s" -ge "$want" ] && { log "$n at step $s -- steady"; return 0; }
    alive "$n" || { log "ABORT: $n is not running"; return 1; }
    sleep 60; t=$((t+60))
  done
}

# * PICK THE EMPTIER CARD AT LAUNCH TIME.  DDP does not split memory evenly
# between ranks, so a hard-coded card hands the bench a whole GPU in one run and
# scraps in the next.
pick_gpu(){
  nvidia-smi --query-gpu=index,memory.free --format=csv,noheader,nounits \
    | sort -t, -k2 -n -r | head -1 | cut -d, -f1 | tr -d ' '
}

mk_method(){ # $1=name $2=step $3=k1|auto
  local n=$1 s=$2 kind=$3
  local src=ckpt_train/$n.step$s.pt dst=bench_ckpt/sd_${n}_step$s.pt
  [ -f "$src" ] || return 1
  [ -f "$dst" ] || python3 experiments/_strip_optim.py "$src" "$dst" >/dev/null 2>&1 || return 1
  local m tmpl
  if [ "$kind" = "k1" ]; then m=sd_${n}s${s}_k1; tmpl=sd_v6gs50_k1.yaml
  else                        m=sd_${n}s${s}_auto; tmpl=sd_v6fs600_auto.yaml; fi
  local cfg=benchmark/configs/methods/$m.yaml
  [ -f "$cfg" ] || sed "s|^_checkpoint:.*|_checkpoint: $(pwd)/$dst|" \
      "benchmark/configs/methods/$tmpl" > "$cfg"
  echo "$m"
}

mk_cfg(){ # $1=file $2=dataset $3=workspace rest=methods
  local f=$1 ds=$2 ws=$3; shift 3
  { echo "# generated by experiments/chain_gtsup.sh"
    echo "workspace: $ws"; echo "datasets:"; echo "  - $ds"; echo "methods:"
    for m in "$@"; do echo "  - $m"; done
    echo "evaluation:"
    echo "  traj: {enable: true, vis: false}"
    echo "  auc: {enable: true, vis: false, aggregation: both}"
    echo "  depth: {enable: false}"; echo "  points: {enable: false}"
  } > "$f"
}

run_bench(){ # $1=config stem  $2=gpu
  local c=$1 g=$2
  log "run $c (gpu$g, memory capped at $CAP)"
  GPU=$g THREADS=8 BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh run "configs/$c.yaml" 2>&1 \
    | grep -a --line-buffered -E "Combination \(|Successful:|Total failed|out of memory|rror|Traceback" \
    | sed -u "s/^/  [$c] /"
  GPU=$g BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh evaluate "configs/$c.yaml" 2>&1 \
    | grep -aE "Total success|Total failed|rror" | sed -u "s/^/  [$c] /"
}

build_cfgs(){ # $1=arm -> emits the two config stems it made
  local n=$1 M="" L=""
  for s in $STEPS_K1;   do m=$(mk_method "$n" "$s" k1)   && M="$M $m"; done
  for s in $STEPS_LONG; do m=$(mk_method "$n" "$s" auto) && L="$L $m"; done
  [ -n "$M" ] && mk_cfg benchmark/configs/gtsup_oxford_$n.yaml   oxford      $WS/oxford      base_k1   $M
  [ -n "$L" ] && mk_cfg benchmark/configs/gtsup_oxlong_$n.yaml   oxford_long $WS/oxford_long base_auto $L
}

report(){ python3 experiments/mk_spine_report.py >/dev/null 2>&1; }

case "$PHASE" in
  train|all)
    log "=== baking check: both banks present ==="
    for s in kth_day_10 kth_night_01 kth_night_04 kth_night_05 tuhh_day_02 \
             tuhh_day_03 tuhh_day_04 tuhh_night_07 tuhh_night_08 tuhh_night_09; do
      [ -f "labels/${s}_gt/index.json" ] || { log "MISSING labels/${s}_gt -- run bake_gt_bank.py first"; exit 1; }
    done
    log "=== arm 1: gtsup (GT poses) ==="
    train_done gtsup || alive gtsup || experiments/launch_gtsup.sh gtsup _gt
    wait_arm gtsup || exit 1
    for _ in $(seq 30); do no_trainer_running && break; sleep 20; done
    no_trainer_running || { log "ABORT: a trainer still holds the cards"; exit 1; }

    log "=== arm 2: teasup (teacher labels), scored alongside arm 1 ==="
    train_done teasup || alive teasup || experiments/launch_gtsup.sh teasup ""
    wait_steady teasup 80 || exit 1
    build_cfgs gtsup
    run_bench gtsup_oxford_gtsup "$(pick_gpu)"; report
    run_bench gtsup_oxlong_gtsup "$(pick_gpu)"; report
    wait_arm teasup || exit 1
    ;;
esac

case "$PHASE" in
  eval|all)
    log "=== scoring: whatever is left, both cards free ==="
    build_cfgs gtsup; build_cfgs teasup
    for c in gtsup_oxford_gtsup gtsup_oxford_teasup \
             gtsup_oxlong_gtsup gtsup_oxlong_teasup; do
      [ -f "benchmark/configs/$c.yaml" ] || continue
      run_bench "$c" "$(pick_gpu)"; report
    done
    ;;
esac
log "GTSUP_DONE"
