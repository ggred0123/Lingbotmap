#!/usr/bin/env bash
# Second half of the spine chain: arm B is already training, so this only
# schedules the scoring around it.
#
# ★ WHY THIS REPLACES chain_spine.sh's tail.  The first attempt started arm B
# while a bench was already holding the card.  The benchmark's caching allocator
# never returns memory -- measured 7.9 GB at start and 140 GB six minutes later
# on the 319-frame Oxford grid -- so the trainer, still filling its stream pool,
# died of OOM at step 7 and the chain then waited forever for a run that no
# longer existed.  Two rules come out of that:
#
#   1. The trainer starts FIRST and reaches steady state before any bench does.
#      Arm A survived eleven hours beside three benches because it had already
#      claimed its 131 GB when they grew.
#   2. Every bench runs under BENCH_GPU_MEM_FRACTION, so the worst case is a
#      slow bench rather than a dead twelve-hour run.
set -u
cd "$(dirname "$0")/.."

WS=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws
STEPS_K1=${STEPS_K1:-"50 100 200 300 400 500 600 700 800 900 1000 1100 1200 1250"}
STEPS_LONG=${STEPS_LONG:-"300 1200"}
CAP=${BENCH_GPU_MEM_FRACTION:-0.27}
log(){ echo "[$(date '+%m-%d %H:%M:%S')] [spine2] $*"; }

train_step(){ grep -aoE '^ *\[ *[0-9]+\]' "experiments/logs/train_$1.log" 2>/dev/null | tail -1 | tr -dc 0-9; }

train_done(){
  python3 - "$1" <<'PY' 2>/dev/null
import json, sys
try:
    d = json.load(open(f"experiments/results/train_{sys.argv[1]}.json"))
except Exception:
    sys.exit(1)
sys.exit(0 if d.get("wall_s") else 1)
PY
}

wait_steady(){ # $1=name $2=step to reach
  local n=$1 want=$2 t=0
  log "waiting for $n to reach step $want before any bench touches the cards"
  while :; do
    train_done "$n" && { log "$n already finished"; return 0; }
    local s; s=$(train_step "$n")
    [ -n "${s:-}" ] && [ "$s" -ge "$want" ] && { log "$n at step $s -- steady"; return 0; }
    if ! ps -eo args | grep -q '[l]ingbot_map.train.trainer'; then
      log "ABORT: $n is not running"; return 1
    fi
    sleep 60; t=$((t+60))
  done
}

wait_train(){ # $1=name
  local n=$1 t=0
  log "waiting for $n to finish"
  while ! train_done "$n" && [ "$t" -lt 259200 ]; do
    sleep 120; t=$((t+120))
    [ $((t % 1800)) -eq 0 ] && log "  ... $n at step $(train_step "$n")"
  done
  train_done "$n" || { log "TIMEOUT on $n"; return 1; }
  log "$n finished"
}

mk_method(){ # $1=name $2=step $3=k1|auto
  local n=$1 s=$2 kind=$3
  local src=ckpt_train/$n.step$s.pt dst=bench_ckpt/sd_${n}_step$s.pt
  [ -f "$src" ] || return 1
  [ -f "$dst" ] || python3 experiments/_strip_optim.py "$src" "$dst" >/dev/null 2>&1 || return 1
  local m tmpl
  if [ "$kind" = "k1" ]; then m=sd_${n}s${s}_k1; tmpl=sd_v6gs50_k1.yaml
  else                        m=sd_${n}s${s}_auto; tmpl=sd_v6fs600_auto.yaml; fi
  local cfg=benchmark/configs/methods/$m.yaml
  [ -f "$cfg" ] || sed "s|^_checkpoint:.*|_checkpoint: $(pwd)/$dst|" \
      "benchmark/configs/methods/$tmpl" > "$cfg"
  echo "$m"
}

mk_cfg(){ # $1=file $2=dataset $3=workspace rest=methods
  local f=$1 ds=$2 ws=$3; shift 3
  { echo "# generated by experiments/chain_spine2.sh"
    echo "workspace: $ws"; echo "datasets:"; echo "  - $ds"; echo "methods:"
    for m in "$@"; do echo "  - $m"; done
    echo "evaluation:"
    echo "  traj: {enable: true, vis: false}"
    echo "  auc: {enable: true, vis: false, aggregation: both}"
    echo "  depth: {enable: false}"; echo "  points: {enable: false}"
  } > "$f"
}

# * PICK THE EMPTIER CARD AT LAUNCH TIME.  DDP does not split memory evenly
# between ranks -- arm A sat at 131/122 GB, arm B at 36/161 -- so a hard-coded
# GPU=1 would hand the bench a whole card in one run and 17 GB in the next.
pick_gpu(){
  nvidia-smi --query-gpu=index,memory.free --format=csv,noheader,nounits \
    | sort -t, -k2 -n -r | head -1 | cut -d, -f1 | tr -d ' '
}

run_bench(){ # $1=config stem
  local c=$1 g
  g=$(pick_gpu); g=${g:-1}
  log "run $c (gpu$g, memory capped at $CAP)"
  GPU=$g THREADS=8 BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh run "configs/$c.yaml" 2>&1 \
    | grep -a --line-buffered -E "Combination \(|seams|Successful:|Total failed|out of memory|rror|Traceback" \
    | sed -u "s/^/  [$c] /"
  GPU=$g BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh evaluate "configs/$c.yaml" 2>&1 \
    | grep -aE "Total success|Total failed|rror" | sed -u "s/^/  [$c] /"
}

score_arm(){ # $1=arm
  local n=$1 M="" L=""
  for s in $STEPS_K1; do m=$(mk_method "$n" "$s" k1) && M="$M $m"; done
  for s in $STEPS_LONG; do m=$(mk_method "$n" "$s" auto) && L="$L $m"; done
  [ -n "$M" ] && { mk_cfg benchmark/configs/spine_oxford_$n.yaml oxford $WS/oxford base_k1 $M
                   run_bench spine_oxford_$n; report; }
  [ -n "$L" ] && { mk_cfg benchmark/configs/spine_oxlong_$n.yaml oxford_long $WS/oxford_long base_auto $L
                   run_bench spine_oxlong_$n; report; }
}

report(){
  /NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/.venv-bench/bin/python \
    experiments/rpe_at_k.py --ws $WS/oxford_long --dataset oxford_long \
    --out experiments/results/rpe_at_k_oxford_long.json >/dev/null 2>&1
  python3 experiments/mk_spine_report.py
}

wait_steady s0on 80 || exit 1
log "=== arm A long-horizon cell, alongside arm B ==="
score_arm s0off
log "=== leftover re-anchor point (M=128 on the trained checkpoint) ==="
run_bench rk_oxlong_msweep
report
wait_train s0on || exit 1
log "=== arm B scoring ==="
score_arm s0on
log "SPINE2_DONE"
