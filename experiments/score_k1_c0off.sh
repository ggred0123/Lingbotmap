#!/usr/bin/env bash
# Oxford K=1 grid for the finished off-policy arm.
#
# This is score_arm()'s K1 half from chain_spine_clean.sh, lifted out because the
# chain wants to score both arms and c0on is not finished -- it is stuck at step
# 165 with the on-policy arm's memory problem.  Same templates, same workspace,
# same cap, so the numbers stay comparable to everything already in the ledger.
#
# ★ THE CAP IS NOT OPTIONAL.  A bench here once grew 7.9 GB to 140 GB in six
# minutes and killed a twelve-hour training run.  Nothing is training on this node
# right now, but the cap stays: the container is capped at 200 GB of RAM and this
# box has already produced 41 OOM kills today.
set -u
cd "$(dirname "$0")/.."
ARM=${ARM:-c0off}
WS=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws
STEPS_K1=${STEPS_K1:-"50 100 200 300 400 500 600 700 800 900 1000 1100 1200 1250"}
CAP=${BENCH_GPU_MEM_FRACTION:-0.27}
log(){ echo "[$(date '+%m-%d %H:%M:%S')] [k1] $*"; }

mk_method(){                      # strip the optimizer, then write a method yaml
  local s=$1 src=ckpt_train/$ARM.step$s.pt dst=bench_ckpt/sd_${ARM}_step$s.pt
  [ -f "$src" ] || return 1
  [ -f "$dst" ] || python3 experiments/_strip_optim.py "$src" "$dst" >/dev/null 2>&1 || return 1
  local m=sd_${ARM}s${s}_k1 cfg
  cfg=benchmark/configs/methods/sd_${ARM}s${s}_k1.yaml
  [ -f "$cfg" ] || sed "s|^_checkpoint:.*|_checkpoint: $(pwd)/$dst|" \
      benchmark/configs/methods/sd_v6gs50_k1.yaml > "$cfg"
  echo "$m"
}

M=""
for s in $STEPS_K1; do
  m=$(mk_method "$s") && { M="$M $m"; log "prepared step $s"; } || log "SKIP step $s (no checkpoint)"
done
[ -n "$M" ] || { log "nothing to score"; exit 1; }

CFG=benchmark/configs/clean_oxford_$ARM.yaml
{ echo "# generated by experiments/score_k1_c0off.sh"
  echo "workspace: $WS/oxford"; echo "datasets:"; echo "  - oxford"; echo "methods:"
  echo "  - base_k1"                       # pretrained reference, always first
  for m in $M; do echo "  - $m"; done
  echo "evaluation:"
  echo "  traj: {enable: true, vis: false}"
  echo "  auc: {enable: true, vis: false, aggregation: both}"
  echo "  depth: {enable: false}"; echo "  points: {enable: false}"
} > "$CFG"
log "config $CFG  ($(echo $M | wc -w) checkpoints + base_k1)"

# FORCE_GPU pins the card (the gtabs chain scores an arm on the card its
# trainer just left while the other card is still training); default: emptiest.
G=${FORCE_GPU:-$(nvidia-smi --query-gpu=index,memory.free --format=csv,noheader,nounits \
    | sort -t, -k2 -n -r | head -1 | cut -d, -f1 | tr -d ' ')}; G=${G:-0}
log "run on gpu$G, cap $CAP"
GPU=$G THREADS=8 BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh run "configs/clean_oxford_$ARM.yaml" 2>&1 \
  | grep -a --line-buffered -E "Combination \(|Successful:|Total failed|out of memory|rror|Traceback" \
  | sed -u "s/^/  [run] /"
log "evaluate"
GPU=$G BENCH_GPU_MEM_FRACTION=$CAP ./benchmark/bench.sh evaluate "configs/clean_oxford_$ARM.yaml" 2>&1 \
  | grep -aE "Total success|Total failed|rror" | sed -u "s/^/  [eval] /"
python3 experiments/mk_spine_report.py >/dev/null 2>&1 && log "report refreshed"
log "K1_DONE"
