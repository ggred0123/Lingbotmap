#!/usr/bin/env bash
# Benchmark a4 (lam_fresh=4.0) once it finishes, on the same axes as a3/a2pc.
# Includes the early checkpoints from the start: K=1 degrades with training, so
# the interesting question for a4 is where ITS optimum sits, not just s300.
#
#   tmux new-session -d -s chain_a4 experiments/chain_a4_eval.sh
set -u
cd "$(dirname "$0")/.."
LOG=experiments/logs/chain_a4.log
exec > >(tee -a "$LOG") 2>&1
log() { echo "[$(date '+%F %T')] [a4-eval] $*"; }

STEPS_TO_EVAL="50 100 150 200 250 300"

log "waiting for train_a4 to be launched"
while ! tmux has-session -t train_a4 2>/dev/null; do sleep 60; done
log "train_a4 is up -- waiting for it to finish"
while tmux has-session -t train_a4 2>/dev/null; do sleep 60; done
log "train_a4 is gone"
sleep 30

METHODS=""
for S in $STEPS_TO_EVAL; do
  SRC="ckpt_train/a4.step${S}.pt" DST="bench_ckpt/sd_a4_step${S}.pt"
  if [ ! -f "$SRC" ]; then log "MISSING $SRC -- skipping"; continue; fi
  if [ ! -f "$DST" ]; then
    log "exporting $SRC -> $DST"
    python experiments/_strip_optim.py "$SRC" "$DST" || { log "EXPORT FAILED $SRC"; continue; }
  fi
  for V in h64 k28; do
    DSTC="benchmark/configs/methods/sd_a4s${S}_${V}.yaml"
    if [ ! -f "$DSTC" ]; then
      sed -e "s|sd_a2_step250\.pt|sd_a4_step${S}.pt|" \
          -e "s|^# self-distilled A2 preset, step 250.*|# a4 step ${S} (walk, lam_fresh=4.0) -- generated by chain_a4_eval.sh|" \
          "benchmark/configs/methods/sd_a2s250_${V}.yaml" > "$DSTC"
      log "wrote $DSTC"
    fi
    METHODS="$METHODS  - sd_a4s${S}_${V}\n"
  done
done

[ -n "$METHODS" ] || { log "NO a4 method configs -- nothing to evaluate"; exit 1; }

{
  echo "# Oxford Spires - a4 (walk, lam_fresh=4.0), K=1 vs K=28, all checkpoints."
  echo "workspace: /NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws/oxford"
  echo ""
  echo "datasets:"
  echo "  - oxford"
  echo ""
  echo "methods:"
  printf "%b" "$METHODS"
  echo "evaluation:"
  echo "  traj:"
  echo "    enable: true"
  echo "    vis: true"
  echo "  auc:"
  echo "    enable: true"
  echo "    vis: true"
  echo "    aggregation: both"
  echo "  depth:"
  echo "    enable: false"
  echo "  points:"
  echo "    enable: false"
} > benchmark/configs/oxford_a4.yaml
log "wrote benchmark/configs/oxford_a4.yaml"

log "Oxford run phase"
benchmark/bench.sh run configs/oxford_a4.yaml --debug || log "BENCH RUN FAILED"
log "Oxford evaluate phase"
benchmark/bench.sh evaluate configs/oxford_a4.yaml --debug || log "BENCH EVALUATE FAILED"
log "A4 CAMPAIGN COMPLETE"
