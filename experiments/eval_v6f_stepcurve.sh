#!/usr/bin/env bash
# Oxford (stride 12) K=1 for every v6f checkpoint that exists -- the step curve
# on the one metric where any distilled cell has beaten the released model.
#
# ★ K=1 ON OXFORD IS THE PAPER'S NUMBER.  sd_v6cs300 is the only checkpoint below
# base there (ATE 5.714 vs 6.150 over 10 scenes); every other cell, including
# v6a at both 300 and 600, loses.  A step curve is needed because v6a's own MCD
# curve peaked at 600 and had collapsed by 1250 -- with only 7 steps evaluated
# nobody could say where between them it turned.
#
# ★ SKIP CHECKPOINTS STILL BEING WRITTEN.  v6f may still be training, and
# torch.save is not atomic: a file younger than 2 minutes can be half-written,
# and _strip_optim would then export garbage that loads and scores wrong.
#
# ★ RE-RUNNABLE.  bench.sh writes .complete.json per (scene, method), so a kill
# costs only the scene in flight and a second invocation resumes.
#
#   experiments/eval_v6f_stepcurve.sh            # export + run both cards
#   NAME=v6g experiments/eval_v6f_stepcurve.sh   # same for another run
set -u
cd "$(dirname "$0")/.."
NAME=${NAME:-v6f}
STRIDE=${STRIDE:-1}          # take every STRIDE-th checkpoint
log(){ echo "[$(date '+%H:%M:%S')] [eval $NAME] $*"; }

# ★ ONLY_STEPS OVERRIDES THE GLOB, AND IS NOT CALLED "STEPS".  launch_v7*.sh
# exports STEPS as the training step budget; reusing that name here would make a
# shell that had just launched training silently score the single step 1250.
STEPS=${ONLY_STEPS:-$(ls -1 ckpt_train/${NAME}.step*.pt 2>/dev/null \
        | sed 's/.*step\([0-9]*\)\.pt/\1/' | sort -n)}
[ -n "$STEPS" ] || { log "no ckpt_train/${NAME}.step*.pt"; exit 1; }

READY=""
i=0
for S in $STEPS; do
  f="ckpt_train/${NAME}.step${S}.pt"
  if [ -z "$(find "$f" -mmin +2 2>/dev/null)" ]; then
    log "skip step $S -- written less than 2 min ago, may be incomplete"; continue
  fi
  i=$(( i + 1 )); [ $(( i % STRIDE )) -ne 0 ] && continue
  READY="$READY $S"
done
log "checkpoints:$READY"
# ★ DRY BEFORE THE EXPORT, not after: stripping 23 x 4.4 GB is minutes of work
# and a dry run that does it is not a dry run.
[ "${DRY:-0}" = "1" ] && { log "DRY=1: would export and score$READY"; exit 0; }

# ── export weights + write one method config each ────────────────────────────
METHODS=""
for S in $READY; do
  DST="bench_ckpt/sd_${NAME}_step${S}.pt"
  [ -f "$DST" ] || { log "export step $S"; python experiments/_strip_optim.py \
      "ckpt_train/${NAME}.step${S}.pt" "$DST" >/dev/null || { log "EXPORT FAILED $S"; continue; }; }
  M="sd_${NAME}s${S}_k1"
  CFG="benchmark/configs/methods/${M}.yaml"
  [ -f "$CFG" ] || sed "s|^_checkpoint:.*|_checkpoint: $(pwd)/${DST}|" \
      benchmark/configs/methods/sd_v6cs300_k1.yaml > "$CFG"
  METHODS="$METHODS $M"
done
set -- $METHODS
log "$# methods"

# ── split across the two cards ───────────────────────────────────────────────
mk(){ # $1=file  rest=methods
  local f=$1; shift
  { echo "# generated by experiments/eval_v6f_stepcurve.sh"
    echo "workspace: /NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws/oxford"
    echo "datasets:"; echo "  - oxford"; echo "methods:"
    for m in "$@"; do echo "  - $m"; done
    echo "evaluation:"
    echo "  traj: {enable: true, vis: false}"
    echo "  auc: {enable: true, vis: false, aggregation: both}"
    echo "  depth: {enable: false}"; echo "  points: {enable: false}"
  } > "$f"
}
A=""; B=""; n=0
for m in "$@"; do n=$(( n + 1 )); if [ $(( n % 2 )) -eq 1 ]; then A="$A $m"; else B="$B $m"; fi; done
mk benchmark/configs/${NAME}_stepcurve_a.yaml $A
mk benchmark/configs/${NAME}_stepcurve_b.yaml $B
mk benchmark/configs/${NAME}_stepcurve_all.yaml base_k1 "$@"
log "gpu0:$A"
log "gpu1:$B"

cd benchmark
F="Combination \(|Successful:|Total failed|already complete|rror|Traceback"
GPU=0 THREADS=8 ./bench.sh run configs/${NAME}_stepcurve_a.yaml 2>&1 | grep -aE "$F" | sed -u 's/^/[gpu0] /' & PA=$!
GPU=1 THREADS=8 ./bench.sh run configs/${NAME}_stepcurve_b.yaml 2>&1 | grep -aE "$F" | sed -u 's/^/[gpu1] /' & PB=$!
wait $PA; log "gpu0 done"
wait $PB; log "gpu1 done"
log "=== EVALUATE ==="
GPU=1 ./bench.sh evaluate configs/${NAME}_stepcurve_all.yaml 2>&1 \
  | grep -aE "Total success|Total failed|rror|Traceback"
log "STEPCURVE_DONE"
