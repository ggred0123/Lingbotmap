#!/usr/bin/env bash
# The spine experiment, end to end, unattended.
#
# docs/eval-metric-audit.html section 10 order 0 and section 11 2a: every run so
# far mixed p_identity 0.1-0.35, so "naive pseudo-label fine-tuning" and "ours"
# have never been separated.  This chain runs the two pure arms and scores both
# on the grid that decides the question.
#
#   arm A  s0off  p_identity = 1.0   identity branch only  (off-policy)
#   arm B  s0on   p_identity = 0.0   correction branch only (on-policy)
#
# ★ ARM A IS ALREADY RUNNING when this script starts; it waits rather than
# launching it, so a restart of the chain never starts a second trainer.
#
# ★ ORDER: training gets both cards, benches share card 1.  Measured here, one
# concurrent bench takes the trainer from ~28 to ~40 s/step -- and the total GPU
# work is the same either way, so the benches run alongside and their results
# land hours earlier, which is the point.
#
# ★ OXFORD K=1 IS THE DECISION GRID, not oxford_long.  auto_eval_v6i.sh's note
# holds: the label probe and Oxford disagree, and every run so far degrades
# monotonically there.  oxford_long (3,840 frames, K=12) is the long-horizon
# cell the project's spine bench asks for and is scored at two steps only,
# because it costs ~48 min per method against ~4 for the K=1 grid.
#
#   experiments/chain_spine.sh                 # full chain
#   PHASE=evalA experiments/chain_spine.sh     # one phase only
set -u
cd "$(dirname "$0")/.."

STEPS_K1=${STEPS_K1:-"50 100 200 300 400 500 600 700 800 900 1000 1100 1200 1250"}
STEPS_LONG=${STEPS_LONG:-"300 1200"}
WS=/NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/bench_ws
WEIGHTS="mcd:10,slowtv:10,dl3dv:10,scannet:10,replica:5,dynamicreplica:10,unrealstereo4k:15,paralleldomain4d:30"
PHASE=${PHASE:-all}
log(){ echo "[$(date '+%m-%d %H:%M:%S')] [spine] $*"; }

# ── wait until a trainer has actually FINISHED ──────────────────────────────
# ★ NOT "does train_<name>.json exist".  The trainer rewrites that file at every
# --save_every, so it appears at step 50 with wall_s = null.  An earlier version
# of this chain took that as completion and launched arm B on top of arm A; the
# second run died on GPU memory within 30 s.  wall_s is written once, at the end,
# so it is the only field that means finished.
train_done(){ # $1=name
  python3 - "$1" <<'PY' 2>/dev/null
import json, sys
try:
    d = json.load(open(f"experiments/results/train_{sys.argv[1]}.json"))
except Exception:
    sys.exit(1)
sys.exit(0 if d.get("wall_s") else 1)
PY
}

wait_train(){ # $1=name  $2=max seconds
  local n=$1 max=${2:-259200} t=0
  log "waiting for $n to finish (wall_s in experiments/results/train_$n.json)"
  while ! train_done "$n" && [ "$t" -lt "$max" ]; do
    sleep 120; t=$((t+120))
    [ $((t % 1800)) -eq 0 ] && log "  ... $n at step $(grep -aoE '^ *\[ *[0-9]+\]' experiments/logs/train_$n.log 2>/dev/null | tail -1 | tr -dc 0-9)"
  done
  train_done "$n" || { log "TIMEOUT waiting for $n"; return 1; }
  log "$n finished"
}

# ★ ONE TRAINER AT A TIME.  Two 1250-step runs do not fit on these two cards
# together -- arm A alone holds 131 GB on card 0 and 122 GB on card 1.
no_trainer_running(){
  [ "$(ps -eo args | grep -c '[l]ingbot_map.train.trainer')" = "0" ]
}

# ── export a checkpoint and write its method config ─────────────────────────
mk_method(){ # $1=name $2=step $3=k1|auto  -> echoes the method id, or nothing
  local n=$1 s=$2 kind=$3
  local src=ckpt_train/$n.step$s.pt dst=bench_ckpt/sd_${n}_step$s.pt
  [ -f "$src" ] || return 1
  if [ ! -f "$dst" ]; then
    python3 experiments/_strip_optim.py "$src" "$dst" >/dev/null 2>&1 || return 1
  fi
  local m tmpl
  if [ "$kind" = "k1" ]; then m=sd_${n}s${s}_k1; tmpl=sd_v6gs50_k1.yaml
  else                        m=sd_${n}s${s}_auto; tmpl=sd_v6fs600_auto.yaml; fi
  local cfg=benchmark/configs/methods/$m.yaml
  [ -f "$cfg" ] || sed "s|^_checkpoint:.*|_checkpoint: $(pwd)/$dst|" \
      "benchmark/configs/methods/$tmpl" > "$cfg"
  echo "$m"
}

mk_bench_cfg(){ # $1=file $2=dataset $3=workspace  rest=methods
  local f=$1 ds=$2 ws=$3; shift 3
  { echo "# generated by experiments/chain_spine.sh"
    echo "workspace: $ws"; echo "datasets:"; echo "  - $ds"; echo "methods:"
    for m in "$@"; do echo "  - $m"; done
    echo "evaluation:"
    echo "  traj: {enable: true, vis: false}"
    echo "  auc: {enable: true, vis: false, aggregation: both}"
    echo "  depth: {enable: false}"; echo "  points: {enable: false}"
  } > "$f"
}

run_bench(){ # $1=config-stem $2=gpu
  local c=$1 g=${2:-1}
  log "run  $c on gpu$g"
  GPU=$g THREADS=8 ./benchmark/bench.sh run "configs/$c.yaml" 2>&1 \
    | grep -aE "Combination \(|Scenes to process|Successful:|Total failed|already complete|out of memory|rror|Traceback" \
    | sed -u "s/^/  [$c] /"
  log "evaluate $c"
  GPU=$g ./benchmark/bench.sh evaluate "configs/$c.yaml" 2>&1 \
    | grep -aE "Total success|Total failed|rror" | sed -u "s/^/  [$c] /"
}

# ── the K=1 decision grid for one arm ───────────────────────────────────────
eval_k1(){ # $1=arm
  local n=$1 M=""
  for s in $STEPS_K1; do
    m=$(mk_method "$n" "$s" k1) && M="$M $m" || log "  skip $n s$s (no checkpoint)"
  done
  [ -n "$M" ] || { log "no $n checkpoints for the K=1 grid"; return 1; }
  mk_bench_cfg benchmark/configs/spine_oxford_$n.yaml oxford $WS/oxford base_k1 $M
  run_bench spine_oxford_$n 1
}

eval_long(){ # $1=arm
  local n=$1 M=""
  for s in $STEPS_LONG; do
    m=$(mk_method "$n" "$s" auto) && M="$M $m" || log "  skip $n s$s (no checkpoint)"
  done
  [ -n "$M" ] || { log "no $n checkpoints for oxford_long"; return 1; }
  mk_bench_cfg benchmark/configs/spine_oxlong_$n.yaml oxford_long $WS/oxford_long base_auto $M
  run_bench spine_oxlong_$n 1
}

report(){
  /NHNHOME/WORKSPACE/26msit001_A/bispl_lab/youngmin/.venv-bench/bin/python \
    experiments/rpe_at_k.py --ws $WS/oxford_long --dataset oxford_long \
    --out experiments/results/rpe_at_k_oxford_long.json >/dev/null 2>&1
  python3 experiments/mk_spine_report.py
}

case "$PHASE" in
  evalA)  eval_k1 s0off; eval_long s0off; report ;;
  evalB)  eval_k1 s0on;  eval_long s0on;  report ;;
  all)
    wait_train s0off || exit 1
    # Ranks can outlive the result file by a few seconds; give the cards back.
    for _ in $(seq 30); do no_trainer_running && break; sleep 20; done
    no_trainer_running || { log "ABORT: a trainer is still holding the GPUs"; exit 1; }
    log "=== launching arm B (p_identity = 0.0) ==="
    NAME=s0on STEPS=1250 P_IDENTITY=0.0 NPROC=2 DATASET_WEIGHTS="$WEIGHTS" \
      experiments/launch_v6.sh --wandb_name s0on --wandb_group spine \
      --wandb_tags spine onpolicy p_identity0
    sleep 300
    if ! ps -eo args | grep -q '[l]ingbot_map.train.trainer'; then
      log "ABORT: arm B died during startup -- see experiments/logs/train_s0on.log"
      tail -20 experiments/logs/train_s0on.log | sed 's/^/  /'
      exit 1
    fi
    log "=== arm A scoring, alongside arm B's training ==="
    eval_k1 s0off; report
    eval_long s0off; report
    wait_train s0on || exit 1
    log "=== arm B scoring ==="
    eval_k1 s0on; report
    eval_long s0on; report
    log "SPINE_CHAIN_DONE"
    ;;
  *) echo "PHASE must be all|evalA|evalB"; exit 2 ;;
esac
